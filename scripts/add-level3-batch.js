const lines = [];
for (const [word, definition] of Object.entries(definitions)) {
  if (existing.has(word)) {
    continue;
  }
  lines.push(
    [
      3,
      word,
      definition,
      "a different academic idea",
      "an unrelated practical concept",
      1,
      `${capitalize(word)} means ${definition}.`,
      "approved"
    ]
      .map(csvEscape)
      .join(",")
  );
  existing.add(word);
}

fs.appendFileSync(filePath, `${lines.join("\n")}\n`);
console.log(`Added ${lines.length} Level 3 words.`);

function csvEscape(value) {
  const text = String(value);
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

function capitalize(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}
